test("the office search filters both sections and Escape clears it", async ({ page }) => {
  await withChatFixtures(page)
  await page.goto("/office")
  const search = page.getByRole("searchbox", { name: "Search office" })
  const templates = page.getByRole("region", { name: "Templates" }).getByRole("button")
  const items = page.getByRole("region", { name: "Items" }).getByRole("button")
  await search.fill("portfolio")
  await expect(templates).toHaveCount(1)
  await expect(items).toHaveCount(1)
  await search.fill("zzzz")
  await expect(page.getByText("No templates match. Pick another kind or clear the search.")).toBeVisible()
  await expect(page.getByText("No items match. Pick another kind or clear the search.")).toBeVisible()
  await search.press("Escape")
  await expect(templates).toHaveCount(5)
  await expect(items).toHaveCount(2)
})

